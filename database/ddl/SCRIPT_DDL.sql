-- Historial de precios acordados vs. realmente comprados (Compras)
CREATE OR REPLACE VIEW VW_COM_PRECIO_HISTORIAL AS
SELECT
    O.ID_PROVEEDOR,
    OD.ID_ARTICULO,
    OD.PRECIO_UNITARIO         AS PRECIO_ACORDADO,
    OD.PORCENTAJE_DESCUENTO,
    OD.PORCENTAJE_IMPUESTO,
    RD.CANTIDAD_RECIBIDA       AS CANTIDAD_REAL_COMPRADA,
    R.FECHA_RECEPCION          AS FECHA_COMPRA,
    O.ID_MONEDA,
    O.TASA_CAMBIO
FROM COM_RECEPCION R
JOIN COM_RECEPCION_DETALLE RD ON R.ID_RECEPCION = RD.ID_RECEPCION
JOIN COM_ORDEN_COMPRA_DETALLE OD ON RD.ID_OC_DETALLE = OD.ID_OC_DETALLE
JOIN COM_ORDEN_COMPRA O ON OD.ID_ORDEN_COMPRA = O.ID_ORDEN_COMPRA
WHERE OD.ID_ARTICULO IS NOT NULL
  AND RD.CANTIDAD_RECIBIDA > 0;

-- Motor de saldos: aplica automaticamente notas de credito/debito certificadas a la cuenta por cobrar
CREATE OR REPLACE TRIGGER TRG_CXC_APLICAR_AFECTACION_SAT
AFTER UPDATE OF ESTADO_FEL ON CXC_DOCUMENTO_VENTA
FOR EACH ROW
WHEN (NEW.ESTADO_FEL = 'CERTIFICADA' AND OLD.ESTADO_FEL <> 'CERTIFICADA' AND NEW.ID_DOCUMENTO_AFECTADO IS NOT NULL)
DECLARE
    v_id_cxc        NUMBER(19);
    v_nuevo_saldo   NUMBER(12,2);
    v_estado_actual VARCHAR2(20);
BEGIN
    BEGIN
        SELECT ID_CXC, SALDO_PENDIENTE, ESTADO_CXC
          INTO v_id_cxc, v_nuevo_saldo, v_estado_actual
          FROM CXC_CUENTA_POR_COBRAR
         WHERE ID_DOCUMENTO = :NEW.ID_DOCUMENTO_AFECTADO;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            v_id_cxc := NULL;
    END;

    IF v_id_cxc IS NOT NULL THEN
        IF :NEW.TIPO_DOCUMENTO = 'NOTA_CREDITO' THEN
            v_nuevo_saldo := v_nuevo_saldo - :NEW.MONTO_TOTAL;
            INSERT INTO CXC_TRANSACCION_AJUSTE (ID_CXC, ID_DOCUMENTO, TIPO_AJUSTE, MONTO_APLICADO)
            VALUES (v_id_cxc, :NEW.ID_DOCUMENTO, 'REBAJA_NC', :NEW.MONTO_TOTAL);
        ELSIF :NEW.TIPO_DOCUMENTO = 'NOTA_DEBITO' THEN
            v_nuevo_saldo := v_nuevo_saldo + :NEW.MONTO_TOTAL;
            INSERT INTO CXC_TRANSACCION_AJUSTE (ID_CXC, ID_DOCUMENTO, TIPO_AJUSTE, MONTO_APLICADO)
            VALUES (v_id_cxc, :NEW.ID_DOCUMENTO, 'RECARGO_ND', :NEW.MONTO_TOTAL);
        END IF;

        IF v_nuevo_saldo < 0 THEN
            v_estado_actual := 'SALDO_A_FAVOR';
        ELSIF v_nuevo_saldo = 0 THEN
            v_estado_actual := 'PAGADA';
        END IF;

        UPDATE CXC_CUENTA_POR_COBRAR
           SET SALDO_PENDIENTE = v_nuevo_saldo,
               ESTADO_CXC = v_estado_actual
         WHERE ID_CXC = v_id_cxc;
    END IF;
END;
