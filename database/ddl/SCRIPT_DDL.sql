-- ============ Modulo de Seguridad (RBAC / Login) ============

-- SEG_USUARIO: Cuentas de acceso al sistema. Reemplaza a USUARIO/CORNERSTONE_USUARIO; ligada 1:1 a un empleado.
CREATE TABLE SEG_USUARIO (
    ID_USUARIO NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ID_EMPLEADO NUMBER NOT NULL UNIQUE,
