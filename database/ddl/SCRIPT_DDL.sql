    FECHA_BLOQUEO TIMESTAMP,
    REQUIERE_CAMBIO_PASSWORD CHAR(1) DEFAULT 'N' CHECK (REQUIERE_CAMBIO_PASSWORD IN ('S','N')),
    ESTADO CHAR(1) DEFAULT 'A' CHECK (ESTADO IN ('A','I')),
    ELIMINADO CHAR(1) DEFAULT 'N' NOT NULL CHECK (ELIMINADO IN ('S','N')),
    FECHA_ELIMINACION TIMESTAMP,
    ELIMINADO_POR NUMBER,
    CONSTRAINT PK_SEG_USUARIO PRIMARY KEY (ID_USUARIO)
