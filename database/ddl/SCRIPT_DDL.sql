-- ========================================================================================
-- SCRIPT DE CREACION DE BASE DE DATOS v2 - ORACLE 12c+
-- Sistema Integrado: Seguridad(RBAC) | Nomina | Cuentas por Cobrar | Cuentas por Pagar
--                    Gestion de Compras | Inventarios
-- 104 tablas. Incorpora: prefijo de tablas por modulo, borrado logico estandar,
-- RBAC completo, catalogo unificado de unidad de medida, rediseno completo de Compras y CxC
-- (segun archivos complementarios verificados), consolidacion de recepcion de proveedor.
-- Ejecutable de principio a fin en una sola pasada:
--   Fase 1: crear todas las tablas sin llaves foraneas
--   Fase 2: agregar llaves foraneas via ALTER TABLE (resuelve dependencias circulares)
--   Fase 3: crear indices sobre columnas de llave foranea
--   Fase 4: vista y trigger de logica de negocio
-- ========================================================================================

